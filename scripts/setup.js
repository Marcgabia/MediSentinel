// Creates .env with freshly generated secrets (only fills keys that are missing — never overwrites).
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import { fileURLToPath } from 'url';

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const envPath = path.join(root, '.env');
const existing = fs.existsSync(envPath) ? fs.readFileSync(envPath, 'utf8') : '';
const has = (key) => new RegExp(`^${key}=.+`, 'm').test(existing);

const defaults = [
  ['PORT', '3000'],
  ['NODE_ENV', 'development'],
  ['DB_HOST', 'localhost'],
  ['DB_PORT', '3306'],
  ['DB_USER', 'root'],
  ['DB_PASSWORD', ''],
  ['DB_NAME', 'medisentinel_audit'],
  ['DB_TEST_NAME', 'medisentinel_test'],
  ['SESSION_SECRET', crypto.randomBytes(32).toString('hex')],
  ['AUDIT_SIGNING_KEY_ID', `k${new Date().getFullYear()}a`],
  ['AUDIT_SIGNING_KEY', crypto.randomBytes(32).toString('hex')],
  ['CREDENTIAL_ENCRYPTION_KEY', crypto.randomBytes(32).toString('hex')],
  ['ADMIN_INITIAL_USERNAME', 'admin'],
  ['ADMIN_INITIAL_EMAIL', 'admin@medisentinel.local'],
  ['ADMIN_INITIAL_PASSWORD', `Ms-${crypto.randomBytes(9).toString('base64url')}`]
];

const lines = [];
for (const [key, value] of defaults) {
  const presentEmpty = new RegExp(`^${key}=$`, 'm').test(existing);
  if (!has(key) && !presentEmpty) lines.push(`${key}=${value}`);
}

if (!lines.length) {
  console.log('✓ .env already contains every required key — nothing changed.');
} else {
  const header = existing ? '\n# Added by npm run setup\n' : '# MediSentinel environment — generated by `npm run setup`.\n# Keep this file private. Losing AUDIT_SIGNING_KEY makes existing records unverifiable;\n# losing CREDENTIAL_ENCRYPTION_KEY invalidates all integration credentials.\n';
  fs.writeFileSync(envPath, `${existing}${header}${lines.join('\n')}\n`);
  console.log(`✓ wrote ${lines.length} setting(s) to .env: ${lines.map((l) => l.split('=')[0]).join(', ')}`);
  const pw = lines.find((l) => l.startsWith('ADMIN_INITIAL_PASSWORD='));
  if (pw) console.log(`  initial admin password: ${pw.split('=')[1]}  (used only when the first account is created)`);
}
